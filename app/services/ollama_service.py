"""Client for communicating with the local Ollama API."""

import httpx

from app.config.settings import (
    OLLAMA_BASE_URL,
    OLLAMA_MODEL,
    OLLAMA_TIMEOUT_SECONDS,
)


class OllamaClient:
    """
    Handle communication between Checkmate and the local Ollama service.

    The client sends source code to the configured language model and
    returns the AI-generated code review report.
    """

    def __init__(self):
        """
        Initialize the Ollama client using centralized application settings.

        Keeping these values in the configuration module ensures that
        connection details are managed consistently across the application.
        """

        # Store the Ollama server address and remove any trailing slash.
        # This prevents malformed URLs when constructing API request paths.
        self.base_url = OLLAMA_BASE_URL.rstrip("/")

        # Select the language model configured for code reviews.
        self.model = OLLAMA_MODEL

        # Set the maximum time to wait for Ollama to generate a response.
        # AI-generated reviews may take longer than ordinary API requests.
        self.timeout = OLLAMA_TIMEOUT_SECONDS

    async def review_code(
        self,
        file_path: str,
        code: str,
    ) -> str:
        """
        Submit a source file to Ollama and return its code review.

        Args:
            file_path: Repository path of the file being reviewed.
            code: Source code content that needs to be analyzed.

        Returns:
            str: Markdown-formatted code review generated by Ollama.

        Raises:
            httpx.HTTPStatusError: If Ollama returns an unsuccessful HTTP status.
            httpx.RequestError: If the request cannot reach the Ollama server.
            RuntimeError: If Ollama returns an empty review.
        """

        # Construct the review instructions sent to the language model.
        # Including the file path helps the model understand the context
        # of the source code being analyzed.
        prompt = f"""
You are a careful senior software engineer performing a code review.

Review the following changed file.

File path: {file_path}

Look for:
1. Bugs and incorrect logic
2. Security vulnerabilities
3. Error-handling problems
4. Performance issues
5. Maintainability concerns

Only report issues supported by the code. Do not invent problems.
If you find no issues, say so clearly.
For each finding, explain the problem, its severity, and a suggested fix.

Return a readable Markdown report.

Code to review:
```text
{code}
```
"""

        # Prepare the request body expected by Ollama's chat API.
        # The messages field contains the instructions and source code,
        # while stream=False requests one complete response.
        payload = {
            "model": self.model,
            "messages": [
                {
                    "role": "user",
                    "content": prompt,
                }
            ],
            "stream": False,
        }

        # Create an asynchronous HTTP client so the FastAPI application
        # can communicate with Ollama without blocking other requests.
        async with httpx.AsyncClient(
            timeout=self.timeout
        ) as client:

            # Send the review request to Ollama's local chat endpoint.
            response = await client.post(
                f"{self.base_url}/api/chat",
                json=payload,
            )

            # Raise an exception if Ollama responds with an HTTP error.
            # This prevents unsuccessful API responses from being treated
            # as valid code review results.
            response.raise_for_status()

            # Convert Ollama's JSON response into a Python dictionary.
            result = response.json()

        # Extract the generated review text from Ollama's response.
        # The message/content fields contain the model's actual output.
        review = result.get("message", {}).get("content")

        # Validate the response before returning it to the review service.
        # An empty response cannot be used as a meaningful code review.
        if not review:
            raise RuntimeError(
                "Ollama returned an empty review."
            )

        # Remove unnecessary whitespace around the generated report
        # and return the final Markdown review to the calling service.
        return review.strip()
